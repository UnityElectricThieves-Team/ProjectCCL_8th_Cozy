// ============================================================
// WindowMode
//
// 앱이 가질 수 있는 고수준 창 모드. WindowState로 매핑되는 정책 단위.
// 잠금·방해금지는 현재 동일한 창 거동(전체 클릭 통과)이라 PassThrough 하나로 묶는다.
// 추후 거동이 갈라지면(예: 방해금지는 topmost 유지) 값을 분리하면 된다.
// ============================================================
public enum eWindowMode
{
    /// <summary>평상시 — 캐릭터 클릭 가능, 빈 공간 통과, 항상 위.</summary>
    Normal,

    /// <summary>잠금/방해금지 — 캐릭터 포함 전부 통과, 뒷창 사용 가능.</summary>
    PassThrough,

    /// <summary>화면 영역 수정 — 불투명·클릭 통과 OFF, 가장자리 리사이즈 + 상단바 이동 활성.</summary>
    EditRegion,
}
